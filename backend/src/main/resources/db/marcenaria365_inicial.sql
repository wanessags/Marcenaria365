BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    telefone VARCHAR(20),
    nome_negocio VARCHAR(120),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    telefone VARCHAR(20),
    email VARCHAR(160),
    endereco TEXT,
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS materiais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL UNIQUE,
    categoria VARCHAR(80),
    unidade VARCHAR(20) NOT NULL DEFAULT 'un',
    quantidade_estoque NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (quantidade_estoque >= 0),
    estoque_minimo NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (estoque_minimo >= 0),
    custo_unitario NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (custo_unitario >= 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS servicos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    titulo VARCHAR(160) NOT NULL,
    descricao TEXT,
    status VARCHAR(25) NOT NULL DEFAULT 'AGUARDANDO' CHECK (status IN ('AGUARDANDO','EM_ANDAMENTO','CONCLUIDO','CANCELADO')),
    data_inicio DATE,
    prazo DATE,
    data_conclusao DATE,
    custo_previsto NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (custo_previsto >= 0),
    valor_cobrado NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (valor_cobrado >= 0),
    observacoes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS servico_materiais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servico_id BIGINT NOT NULL REFERENCES servicos(id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES materiais(id),
    quantidade NUMERIC(12,2) NOT NULL CHECK (quantidade > 0),
    custo_unitario NUMERIC(12,2) NOT NULL CHECK (custo_unitario >= 0),
    UNIQUE (servico_id, material_id)
);

CREATE TABLE IF NOT EXISTS orcamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id),
    servico_id BIGINT REFERENCES servicos(id),
    status VARCHAR(20) NOT NULL DEFAULT 'RASCUNHO' CHECK (status IN ('RASCUNHO','ENVIADO','APROVADO','RECUSADO')),
    data_emissao DATE NOT NULL DEFAULT CURRENT_DATE,
    validade DATE,
    observacoes TEXT,
    desconto NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (desconto >= 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS orcamento_itens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orcamento_id BIGINT NOT NULL REFERENCES orcamentos(id) ON DELETE CASCADE,
    descricao VARCHAR(200) NOT NULL,
    quantidade NUMERIC(12,2) NOT NULL CHECK (quantidade > 0),
    valor_unitario NUMERIC(12,2) NOT NULL CHECK (valor_unitario >= 0)
);

CREATE TABLE IF NOT EXISTS recebimentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servico_id BIGINT NOT NULL REFERENCES servicos(id),
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    forma_pagamento VARCHAR(20) CHECK (forma_pagamento IN ('PIX','DINHEIRO','CARTAO','TRANSFERENCIA')),
    status VARCHAR(15) NOT NULL DEFAULT 'PENDENTE' CHECK (status IN ('PENDENTE','RECEBIDO','CANCELADO')),
    data_prevista DATE,
    data_recebimento DATE,
    observacoes TEXT,
    CHECK (status <> 'RECEBIDO' OR data_recebimento IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS movimentacoes_caixa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('ENTRADA','SAIDA')),
    categoria VARCHAR(80) NOT NULL,
    descricao VARCHAR(200) NOT NULL,
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    data_movimentacao DATE NOT NULL DEFAULT CURRENT_DATE,
    recebimento_id BIGINT UNIQUE REFERENCES recebimentos(id),
    CHECK (recebimento_id IS NULL OR tipo = 'ENTRADA')
);

CREATE TABLE IF NOT EXISTS aceites_politica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    versao_politica VARCHAR(20) NOT NULL,
    aceito_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (usuario_id, versao_politica)
);

CREATE INDEX IF NOT EXISTS idx_servicos_cliente ON servicos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_orcamentos_cliente ON orcamentos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_recebimentos_servico ON recebimentos(servico_id);

